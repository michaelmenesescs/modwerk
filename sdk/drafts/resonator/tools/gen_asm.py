#!/usr/bin/env python3
"""Write resonator.asm: the RESONATOR DSP56300 engine.

The four voices are the same code at different state offsets and ring
registers, so they are generated rather than copied by hand; every constant
comes from resonator_ref.py, which is the model this engine must match.

    python3 tools/gen_asm.py            # rewrites ../resonator.asm
    python3 tools/gen_asm.py --check    # exits 1 if resonator.asm is stale

Register and memory plan (FX2 insert, one instance per r7 block):

  x:(r7+8v+k), v = 0..3, k:  0 C  allpass coefficient       1 G   loop gain
                             2 INJ input gain (x D/4)       3 APX allpass x[n-1]
                             4 APY allpass y[n-1] (= FIR z1) 5 Z2  FIR z2
                             6 DS  smoothed delay * 4096     7 OFF semitone offset,
                                                               then -N (the read offset)
  x:(r7+$20) HPM  low-cut x[n-1]     $21 HPH  low-cut y[n-1]    $22 SP  spread
         $23 BF   FIR b              $24 MX   mix               $25 SS  sum y/4
         $26 DD   pan difference     $27 BASE Y buffer base     $28 CLR clear calls left
         $29 WP   write pointer      $2a NB   36 + TUNE         $2b UDC decay exponent
         $2c DRQ  drive D/4          $2d FRZ  freeze flag       $2e TMP exponent
         $2f HPL  low-cut y[n-1], low word
  y:BASE + $800*v .. +$7ff: voice v's ring (modulo $7ff, r2..r5). 8,192 words.

Traps honoured (sdk/octabam/AGENTS.md): no `rep`; only the mpy/mac operand
orders that disassemble as signed (x0,y1 and y0,x0); no one-word displaced Y
moves; Tcc from registers only; clean reloads before tests after a shift;
no label is a prefix of another.
"""
import math
import pathlib
import sys

HERE = pathlib.Path(__file__).resolve().parent
sys.path.insert(0, str(HERE))
import resonator_ref as ref  # noqa: E402

q = ref.q23
POLY, _ = ref.exp2_poly()
K0 = (11.0 - ref.LOG2_FS_A4 - 69 / 12.0) / 16.0
TBL = "$fab1e0"          # the build points this literal at the ptable
AP_AT, CHORD_AT, VOIC_AT = 0, 65, 125
RINGS = ("r2", "r3", "r4", "r5")
NREG = ("n2", "n3", "n4", "n5")


def h(v):
    return f"${v & 0xFFFFFF:06x}"


def x(off):
    return f"x:(r7+${off:02x})"


lines = []


def emit(s=""):
    lines.append(s)


def op(ins, comment=None):
    emit(f"        {ins:<28}" + (f"; {comment}" if comment else "") if comment else f"        {ins}")


def label(name):
    emit(f"{name}:")


def header():
    emit("; RESONATOR 0.1.0 (draft): a four-voice chord resonator insert for FX2.")
    emit("; GENERATED by tools/gen_asm.py from tools/resonator_ref.py -- edit those, not this.")
    emit("; Four tuned feedback combs: ring -> first-order allpass (the fraction) ->")
    emit("; 3-tap FIR [b,1-2b,b] (brightness) -> loop gain g, + input * inj. The store")
    emit("; limiter on the ring write is the clip. Rings: y:BASE+$800*v, 2048 words each,")
    emit("; 8,192 in all, far below the slot's sidechain window at +$3DFE.")
    emit("; State x:(r7+$00..$2e); see gen_asm.py for the map. No global writable state.")
    emit()


def init():
    label("init")
    op("move    #>$ffffff,m4")
    op("move    r7,r4")
    op("clr     a")
    op("do      #64,>rz_izero", "$00..$3f")
    op("move    a,x:(r4)+")
    label("rz_izero")
    op("nop")
    op("move    x:>$213,r4", "the allocator's entry for this instance")
    op("move    x:(r4),a")
    op(f"move    a,{x(0x27)}", "BASE")
    op(f"move    a,{x(0x29)}", "WP: ring 0's write pointer")
    op("move    #>$40,a")
    op(f"move    a,{x(0x28)}", "CLR: 64 calls clear 128 words each")
    op("move    #>$ffffff,a", "DS = -1: snap to the first target")
    for v in range(4):
        op(f"move    a,{x(8 * v + 6)}")
    op("rts")
    emit()


def exp2():
    emit("; a = U/16 in [0,1) -> a = 2^-U (U = k + f; cubic for 0.5*2^-f, then >> k).")
    emit("; Uses b? no: a, x0, x1, y1.")
    label("rz_exp2")
    op("move    a1,x0")
    op("move    x0,a")
    op("asr     #19,a,a", "k = integer part")
    op("move    a1,x1")
    op("move    x0,a")
    op("and     #>$07ffff,a")
    op("asl     #4,a,a", "f in [0,1)")
    op("move    a1,y1")
    op(f"move    #>{h(q(POLY[3]))},x0")
    op("mpy     x0,y1,a")
    op(f"add     #>{h(q(POLY[2]))},a")
    op("move    a,x0")
    op("mpy     x0,y1,a")
    op(f"add     #>{h(q(POLY[1]))},a")
    op("move    a,x0")
    op("mpy     x0,y1,a")
    op(f"add     #>{h(q(POLY[0]))},a", "0.5*2^-f")
    op("asl     #1,a,a", "2^-f, up to 1.0")
    op("asr     x1,a,a", ">> k")
    op("rts")
    emit()


def knob_int(src, shift, dst, clamp=None, sub=None):
    """dst = ((x:src >> shift) & $7f) [clamped] [- sub], clean."""
    op(f"move    {src},a")
    op(f"asr     #{shift},a,a")
    op("move    a1,x0")
    op("move    x0,a")
    op("and     #>$7f,a")
    if clamp is not None:
        op(f"move    #>{clamp},x0")
        op("cmp     x0,a")
        op("tgt     x0,a")
    if sub is not None:
        op(f"sub     #>{sub},a")
    if dst:
        op(f"move    a,{dst}")


def proc():
    label("proc")
    op("move    #>$ffffff,m4")
    op("move    #>$ffffff,m5")
    emit("; Bounded clearing: 64 calls of 128 words, ring 3's top first; the audio")
    emit("; passes through untouched meanwhile.")
    op(f"move    {x(0x28)},a")
    op("tst     a")
    op("beq     rz_live")
    op("sub     #>$1,a")
    op(f"move    a,{x(0x28)}")
    op("asl     #7,a,a")
    op(f"move    {x(0x27)},x0")
    op("add     x0,a")
    op("move    a,r4")
    op("clr     a")
    op("do      #128,>rz_wipe")
    op("move    a,y:(r4)+")
    label("rz_wipe")
    op("nop")
    op("rts")
    label("rz_live")
    emit("; ---- knobs, once per call")
    knob_int("x:(r6)", 16, None)
    op("add     #>36,a", "NB = 36 + TUNE (C2 + TUNE)")
    op(f"move    a,{x(0x2a)}")
    op("move    x:(r6+$1),x0", "DCAY/128")
    op(f"move    #>{h(q(ref.K_D * 128 / 16))},y1")
    op("mpy     x0,y1,a")
    op(f"add     #>{h(q(ref.K_X / 16))},a")
    op(f"move    a,{x(0x2b)}", "UDC = K_X/16 + K_D*DCAY/16")
    op("move    x:(r6+$2),a", "BRIT/128")
    op("asr     #2,a,a")
    op("move    a1,x0")
    op("move    #>$200000,a")
    op("sub     x0,a")
    op(f"move    a,{x(0x23)}", "BF = 0.25 - BRIT/512")
    op("move    x:(r6+$3),a")
    op(f"move    a,{x(0x22)}", "SP = SPRD/128")
    op("move    x:(r6+$4),x0", "DRIV/128")
    op(f"move    #>{h(q(2 * 128 / 127 / 16))},y1")
    op("mpy     x0,y1,b")
    op("move    #>$100000,a")
    op("sub     b,a", "U_D/16 = 0.125 - DRIV*2/127/16")
    op("bsr     rz_exp2")
    op(f"move    a,{x(0x2c)}", "DRQ = D/4")
    op("move    x:(r6+$5),a")
    op("move    #>$7f0000,x0")
    op("cmp     x0,a")
    op("blt     rz_mixok")
    op("move    #>$7fffff,a", "127 is fully wet")
    label("rz_mixok")
    op(f"move    a,{x(0x24)}", "MX")
    op("move    x:(r6+$e),a", "FREZ: slot 11, $e's companion byte")
    op("and     #>$00ff00,a")
    op(f"move    a,{x(0x2d)}")
    emit("; chord offsets into OFF (x:(r7+8v+7)): USER from INT2..4, else the table")
    knob_int("x:(r6+$c)", 16, None, clamp=len(ref.CHORDS) - 1)
    op("tst     a")
    op("bne     rz_preset")
    op("clr     a")
    op(f"move    a,{x(7)}")
    knob_int("x:(r6+$d)", 16, x(15), sub=24)
    knob_int("x:(r6+$d)", 8, x(23), sub=24)
    knob_int("x:(r6+$e)", 16, x(31), sub=24)
    op("bra     rz_voicing")
    label("rz_preset")
    op("asl     #2,a,a")
    op(f"add     #>{CHORD_AT},a")
    op(f"move    #>{TBL},x0")
    op("add     x0,a")
    op("move    a,r5")
    for v in range(4):
        op("move    p:(r5)+,x0")
        op(f"move    x0,{x(8 * v + 7)}")
    label("rz_voicing")
    knob_int("x:(r6+$c)", 8, None, clamp=len(ref.VOICINGS) - 1)
    op("asl     #2,a,a")
    op(f"add     #>{VOIC_AT},a")
    op(f"move    #>{TBL},x0")
    op("add     x0,a")
    op("move    a,r5")
    for v in range(4):
        op(f"move    {x(8 * v + 7)},a")
        op("move    p:(r5)+,x0")
        op("add     x0,a")
        op(f"move    a,{x(8 * v + 7)}")
    for v in range(4):
        voice_setup(v)
    emit("; FREZ: lossless, input closed")
    op(f"move    {x(0x2d)},a")
    op("tst     a")
    op("beq     rz_thaw")
    op("move    #>$7fffff,x0")
    op("clr     a")
    for v in range(4):
        op(f"move    x0,{x(8 * v + 1)}")
        op(f"move    a,{x(8 * v + 2)}")
    op(f"move    a,{x(0x23)}")
    label("rz_thaw")
    sample_loop()


def voice_setup(v):
    V = 8 * v
    tag = "abcd"[v]
    emit(f"; ---- voice {v}: note, delay, allpass, loop gain, input gain")
    op(f"move    {x(0x2a)},a")
    op(f"move    {x(V + 7)},x0")
    op("add     x0,a", "note = NB + OFF")
    op(f"move    #>{ref.LOWEST_NOTE},y0")
    for _ in range(3):
        op("move    a,b")
        op("add     #>12,b")
        op("move    b,x1")
        op("cmp     y0,a")
        op("tlt     x1,a", "below C1: up an octave")
    op(f"move    #>{ref.HIGHEST_NOTE},y0")
    for _ in range(3):
        op("move    a,b")
        op("sub     #>12,b")
        op("move    b,x1")
        op("cmp     y0,a")
        op("tgt     x1,a", "above C8: down an octave")
    op("asl     #16,a,a", "note/128")
    op("move    a,x0")
    op("move    #>$555555,y1")
    op("mpy     x0,y1,a")
    op(f"add     #>{h(q(K0))},a", "U_P/16 = 11 - log2 P, /16")
    op(f"move    a,{x(0x2e)}")
    op("bsr     rz_exp2", "P/2048 = P*4096 as an integer")
    op("sub     #>$1000,a", "target d = P - 1 (the FIR's sample)")
    op(f"move    {x(V + 6)},b")
    op("tst     b")
    op(f"bge     rz_glide{tag}")
    op("move    a1,b", "first call: snap")
    op(f"bra     rz_held{tag}")
    label(f"rz_glide{tag}")
    op("sub     b,a")
    op("asr     #3,a,a")
    op("add     a,b", "DS += (d - DS)/8")
    label(f"rz_held{tag}")
    op(f"move    b1,{x(V + 6)}")
    op(f"move    {x(V + 6)},a")
    op("sub     #>$800,a", "DS - 0.5 sample")
    op("move    a,b")
    op("asr     #12,a,a")
    op("move    a1,x0", "N")
    op("move    x0,a")
    op("neg     a")
    op(f"move    a,{x(V + 7)}", "-N: the read offset")
    op("and     #>$fff,b", "(fraction - 0.5) * 4096")
    op("move    b1,x1")
    op("move    x1,b")
    op("asr     #6,b,b")
    op("move    b1,x0")
    op(f"move    #>{TBL},a")
    op("add     x0,a")
    op("move    a,r5")
    op("move    x1,b")
    op("and     #>$3f,b")
    op("asl     #17,b,b")
    op("move    b1,y1", "interpolation weight")
    op("move    p:(r5)+,y0", "T[i]")
    op("move    p:(r5),a", "T[i+1]")
    op("sub     y0,a")
    op("move    a,x0")
    op("mpy     x0,y1,a")
    op("add     y0,a")
    op(f"move    a,{x(V + 0)}", "C")
    op(f"move    {x(0x2e)},a")
    op(f"move    {x(0x2b)},x0")
    op("add     x0,a")
    op(f"move    a,{x(0x2e)}", "U_x/16, limited below 1")
    op(f"move    {x(0x2e)},a")
    op("bsr     rz_exp2", "x/16")
    op("bsr     rz_exp2", "g = 2^-x")
    op(f"move    a,{x(V + 1)}", "G")
    op(f"move    {x(0x2e)},a")
    op(f"sub     #>{h(q(ref.K_I / 16))},a")
    op("asr     #1,a,a")
    op("move    a1,x0")
    op("move    x0,a")
    op("move    #0,x1")
    op("tst     a")
    op("tmi     x1,a", "at most unity")
    op("bsr     rz_exp2", "inj")
    op("move    a,x0")
    op(f"move    {x(0x2c)},y1")
    op("mpy     x0,y1,a")
    op(f"move    a,{x(V + 2)}", "INJ = inj * D/4")


def sample_loop():
    emit("; ---- the sample loop")
    op(f"move    {x(0x29)},r2", "ring 0 write pointer")
    op(f"move    {x(0x29)},a")
    for r in RINGS[1:]:
        op("add     #>$800,a")
        op(f"move    a,{r}")
    for r in RINGS:
        op(f"move    #>$7ff,m{r[1]}")
    for v, n in enumerate(NREG):
        op(f"move    {x(8 * v + 7)},{n}")
    op("move    #>$1,n0")
    op("move    n7,a")
    op("tst     a")
    op("beq     rz_done")
    op("do      n7,>rz_end")
    op("move    x:(r0),a")
    op("move    x:(r0+n0),x0")
    op("add     x0,a")
    op("asr     #1,a,a")
    op("move    a,x1", "mono, truncated once: m and m[n-1] agree")
    op("move    x1,a")
    op(f"move    {x(0x20)},x0")
    op("sub     x0,a", "m - m[n-1]")
    op(f"move    x1,{x(0x20)}")
    op(f"move    {x(0x21)},b")
    op(f"move    {x(0x2f)},b0", "h[n-1], 48 bits: no deadband")
    op("add     b,a", "s = h[n-1] + m - m[n-1]")
    op("move    a,x0")
    op(f"move    #>{h(q(1.0 - ref.C_HP))},y1")
    op("mac     -x0,y1,a", "h = s - (1-c) s: 60 Hz low cut")
    op(f"move    a1,{x(0x21)}")
    op(f"move    a0,{x(0x2f)}")
    op("rnd     a")
    op("move    a,y0", "y0 = h for every voice")
    for v in range(4):
        V, r, n = 8 * v, RINGS[v], NREG[v]
        emit(f"; voice {v}")
        op(f"move    y:({r}+{n}),x0", "xn")
        op(f"move    {x(V + 3)},a")
        op(f"move    {x(V + 0)},y1")
        op("mac     x0,y1,a")
        op(f"move    x0,{x(V + 3)}")
        op(f"move    {x(V + 4)},x0", "z1")
        op("macr    -x0,y1,a", "y (rounded: no DC bias in the loop)")
        op(f"move    a,{x(V + 4)}")
        op(f"move    {x(V + 5)},b")
        op("add     a,b")
        op("sub     x0,b")
        op("sub     x0,b", "y + z2 - 2 z1")
        op(f"move    x0,{x(V + 5)}")
        op("move    b,x0")
        op(f"move    {x(0x23)},y1")
        op("mpyr    x0,y1,b")
        op(f"move    {x(V + 5)},x0")
        op("add     x0,b", "filt")
        op("move    b,x0")
        op(f"move    {x(V + 1)},y1")
        op("mpy     x0,y1,b")
        op(f"move    {x(V + 2)},x0")
        op("mac     y0,x0,b", "g*filt + inj*h")
        op("tst     b")
        op(f"bge     rz_keep{'abcd'[v]}")
        op("add     #>$1,b", "negative: toward zero, so every ring dies out")
        label(f"rz_keep{'abcd'[v]}")
        op(f"move    b,y:({r})+", "the store limiter is the clip")
        op("asr     #2,a,a", "y/4")
        if v == 0:
            op(f"move    a,{x(0x25)}")
            op("neg     a")
            op(f"move    a,{x(0x26)}")
        else:
            op(f"move    {x(0x25)},b")
            op("add     a,b")
            op(f"move    b,{x(0x25)}")
            if v in (1, 2):
                op("asr     #1,a,a")
            op(f"move    {x(0x26)},b")
            op("sub     a,b" if v == 1 else "add     a,b")
            op(f"move    b,{x(0x26)}")
    for side, mac in (("left", "mac     -x0,y1,a"), ("right", "mac     x0,y1,a")):
        emit(f"; {side}: (S -/+ s*D) * 4, then MIX against the dry")
        op(f"move    {x(0x22)},y1")
        op(f"move    {x(0x26)},x0")
        op(f"move    {x(0x25)},a")
        op(mac)
        op("asl     #2,a,a")
        op("move    x:(r0),b")
        op("sub     b,a")
        op("asr     #3,a,a")
        op("move    a,x0")
        op(f"move    {x(0x24)},y1")
        op("mpy     x0,y1,a")
        op("asl     #3,a,a")
        op("add     b,a")
        op("move    a,x:(r0)+")
    label("rz_end")
    op("nop")
    op(f"move    r2,{x(0x29)}")
    label("rz_done")
    for r in RINGS:
        op(f"move    #>$ffffff,m{r[1]}")
    op("rts")


def build():
    lines.clear()
    header()
    init()
    proc()
    emit()
    exp2()
    names = [l[:-1] for l in lines if l.endswith(":") and not l.startswith(" ")]
    for a in names:
        for b in names:
            if a != b and b.startswith(a):
                raise SystemExit(f"label {a} is a prefix of {b}")
    if any(l.strip().startswith("rep") for l in lines):
        raise SystemExit("rep in source")
    return "\n".join(lines) + "\n"


if __name__ == "__main__":
    out = HERE.parent / "resonator.asm"
    text = build()
    if "--check" in sys.argv:
        sys.exit(0 if out.exists() and out.read_text() == text else 1)
    out.write_text(text)
    print(f"wrote {out} ({sum(1 for l in text.splitlines() if l.startswith('        '))} instructions)")
